"""
Build TFRecord shards from generated clean/noisy WAV pairs.

Each example stores the noisy and clean STFTs (real + imag, normalized by a global
max magnitude). This lets both the cRM U-Net and the magnitude-domain Park R-CED
model derive their own targets from the same shards at training time:

    cRM target (U-Net)     : (clean * conj(noisy)) / (|noisy|^2 + eps)
    Magnitude target (Park): log1p(|clean|)   ; input log1p(|noisy|)

Shards are written to <out-dir>/train/ and <out-dir>/val/ separately so the splits
generated by generate_dataset.py are preserved end-to-end (no speaker leakage).

Parallelism: STFT/numpy work is done in a worker pool; the main process writes
shards. Segment hop defaults to SEGMENT_SAMPLES (no overlap) to keep total data
volume sane; pass --segment-overlap 0.5 to match the legacy v2 pipeline.

Usage (from repo root):
    python scripts/data/build_tfrecords.py \\
        --clean-dir dataset/CleanSpeech_training \\
        --noisy-dir dataset/NoisySpeech_training \\
        --manifest  dataset/dataset_manifest.json \\
        --out-dir   tfrecords_park \\
        --samples-per-shard 1024 \\
        --workers 8 \\
        --segment-overlap 0.0
"""

from __future__ import annotations

import argparse
import json
import multiprocessing as mp
import os
import re
import sys
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path

import numpy as np
import soundfile as sf
import tensorflow as tf
from tqdm import tqdm

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from config import Config, compute_stft  # noqa: E402

NOISY_RE = re.compile(r"noisy(\d+)_SNRdb_([\d.]+)_(clnsp\d+)\.wav$")


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--clean-dir", type=Path, required=True)
    p.add_argument("--noisy-dir", type=Path, required=True)
    p.add_argument("--manifest", type=Path, required=True)
    p.add_argument("--out-dir", type=Path, required=True)
    p.add_argument("--samples-per-shard", type=int, default=1024)
    p.add_argument("--stats-sample-pairs", type=int, default=300)
    p.add_argument("--workers", type=int, default=8)
    p.add_argument("--segment-overlap", type=float, default=0.0,
                   help="Fractional overlap between segments (0.0 = no overlap, 0.5 = 50%%).")
    return p.parse_args()


# ---- TFRecord serialization (in main process) ----

def _float_feature(arr: np.ndarray) -> tf.train.Feature:
    return tf.train.Feature(float_list=tf.train.FloatList(value=arr.astype(np.float32).flatten()))


def _int64_feature(value: int) -> tf.train.Feature:
    return tf.train.Feature(int64_list=tf.train.Int64List(value=[int(value)]))


def serialize_example(noisy_real: np.ndarray, noisy_imag: np.ndarray,
                      clean_real: np.ndarray, clean_imag: np.ndarray,
                      snr: float) -> bytes:
    n_freq, n_time = noisy_real.shape
    feature = {
        "noisy_real": _float_feature(noisy_real),
        "noisy_imag": _float_feature(noisy_imag),
        "clean_real": _float_feature(clean_real),
        "clean_imag": _float_feature(clean_imag),
        "n_freq": _int64_feature(n_freq),
        "n_time": _int64_feature(n_time),
        "snr": _float_feature(np.array([snr], dtype=np.float32)),
    }
    ex = tf.train.Example(features=tf.train.Features(feature=feature))
    return ex.SerializeToString()


# ---- Worker functions ----

def _load_audio(path: Path) -> np.ndarray:
    a, sr = sf.read(str(path), dtype="float32")
    if a.ndim > 1:
        a = a.mean(axis=1)
    if sr != Config.SAMPLE_RATE:
        raise RuntimeError(f"{path}: sr={sr}, expected {Config.SAMPLE_RATE}.")
    return a


def _segment_starts(n_samples: int, seg_samples: int, hop_samples: int) -> list[int]:
    if n_samples < seg_samples:
        return []
    return list(range(0, n_samples - seg_samples + 1, hop_samples))


def _worker_max_mag(noisy_path_str: str) -> float | None:
    try:
        a = _load_audio(Path(noisy_path_str))
        mag = np.abs(compute_stft(a))
        return float(np.percentile(mag, 99.9))
    except Exception as e:
        print(f"skip stats for {noisy_path_str}: {e}", file=sys.stderr)
        return None


def _worker_build_shard(args_tuple) -> tuple[int, int]:
    """Each worker is given a contiguous chunk of pairs and a unique worker_id.
    It writes its own TFRecord shards directly, with no data crossing the process
    boundary. Returns (n_examples, n_shards) for this worker.

    Shard naming: <out_dir>/<prefix>-w{worker_id:03d}-{shard:05d}.tfrecord
    """
    (chunk, max_mag, seg_samples, hop_samples,
     out_dir_str, prefix, worker_id, samples_per_shard) = args_tuple
    out_dir = Path(out_dir_str)
    out_dir.mkdir(parents=True, exist_ok=True)

    n_examples = 0
    shard_idx = 0
    in_shard = 0
    writer = tf.io.TFRecordWriter(
        str(out_dir / f"{prefix}-w{worker_id:03d}-{shard_idx:05d}.tfrecord"))

    try:
        for clean_path_str, noisy_path_str, snr in chunk:
            try:
                clean = _load_audio(Path(clean_path_str))
                noisy = _load_audio(Path(noisy_path_str))
            except Exception as e:
                print(f"[w{worker_id}] skip {noisy_path_str}: {e}", file=sys.stderr)
                continue
            min_len = min(len(clean), len(noisy))
            clean = clean[:min_len]
            noisy = noisy[:min_len]
            starts = _segment_starts(min_len, seg_samples, hop_samples)
            inv = 1.0 / max(max_mag, 1e-8)
            for s in starts:
                c_seg = clean[s:s + seg_samples]
                n_seg = noisy[s:s + seg_samples]
                c_stft = compute_stft(c_seg)
                n_stft = compute_stft(n_seg)
                record = serialize_example(
                    (np.real(n_stft) * inv).astype(np.float32),
                    (np.imag(n_stft) * inv).astype(np.float32),
                    (np.real(c_stft) * inv).astype(np.float32),
                    (np.imag(c_stft) * inv).astype(np.float32),
                    snr,
                )
                if in_shard >= samples_per_shard:
                    writer.close()
                    shard_idx += 1
                    in_shard = 0
                    writer = tf.io.TFRecordWriter(
                        str(out_dir / f"{prefix}-w{worker_id:03d}-{shard_idx:05d}.tfrecord"))
                writer.write(record)
                in_shard += 1
                n_examples += 1
    finally:
        writer.close()
    return n_examples, shard_idx + 1


# ---- Pair collection ----

def collect_pairs(clean_dir: Path, noisy_dir: Path, manifest: dict, split: str
                  ) -> list[tuple[Path, Path, float]]:
    split_ids = {entry["id"] for entry in manifest["splits"][split]}
    pairs: list[tuple[Path, Path, float]] = []
    for p in sorted(noisy_dir.iterdir()):
        m = NOISY_RE.match(p.name)
        if not m:
            continue
        idx = int(m.group(1))
        if idx not in split_ids:
            continue
        snr = float(m.group(2))
        clean_name = m.group(3) + ".wav"
        clean_path = clean_dir / clean_name
        if not clean_path.exists():
            continue
        pairs.append((clean_path, p, snr))
    return pairs


def process_split(pairs: list[tuple[Path, Path, float]],
                  out_dir: Path,
                  max_mag: float,
                  samples_per_shard: int,
                  workers: int,
                  seg_samples: int,
                  hop_samples: int,
                  split: str) -> tuple[int, int]:
    """Each worker is assigned a contiguous chunk of the pairs and writes its own
    shards independently — no large objects cross the process boundary."""
    split_dir = out_dir / split
    split_dir.mkdir(parents=True, exist_ok=True)

    pair_tuples = [(str(c), str(n), s) for c, n, s in pairs]
    # Round-robin split so each worker has a balanced workload.
    chunks: list[list] = [[] for _ in range(workers)]
    for i, item in enumerate(pair_tuples):
        chunks[i % workers].append(item)

    args_per_worker = [
        (chunk, max_mag, seg_samples, hop_samples,
         str(split_dir), split, worker_id, samples_per_shard)
        for worker_id, chunk in enumerate(chunks)
    ]

    n_examples = 0
    n_shards = 0
    with ProcessPoolExecutor(max_workers=workers) as pool:
        with tqdm(total=workers, desc=f"build [{split}] workers") as pbar:
            for n_ex, n_sh in pool.map(_worker_build_shard, args_per_worker):
                n_examples += n_ex
                n_shards += n_sh
                pbar.update(1)
    return n_examples, n_shards


def compute_global_max_mag(noisy_paths: list[Path], n_samples: int, workers: int) -> float:
    rng = np.random.default_rng(0)
    idx = rng.choice(len(noisy_paths), size=min(n_samples, len(noisy_paths)), replace=False)
    sample_paths = [str(noisy_paths[int(i)]) for i in idx]
    pct = []
    with ProcessPoolExecutor(max_workers=workers) as pool:
        for v in tqdm(pool.map(_worker_max_mag, sample_paths, chunksize=8),
                      total=len(sample_paths), desc="max_mag"):
            if v is not None:
                pct.append(v)
    if not pct:
        raise RuntimeError("No max_mag samples processed.")
    return float(np.max(pct))


def main() -> None:
    args = parse_args()
    manifest = json.loads(args.manifest.read_text())

    args.out_dir.mkdir(parents=True, exist_ok=True)
    print("Collecting pairs...")
    train_pairs = collect_pairs(args.clean_dir, args.noisy_dir, manifest, "train")
    val_pairs = collect_pairs(args.clean_dir, args.noisy_dir, manifest, "val")
    print(f"  train: {len(train_pairs)}  val: {len(val_pairs)}")
    if not train_pairs or not val_pairs:
        raise RuntimeError("Empty split. Did generate_dataset.py run successfully?")

    seg_samples = Config.SEGMENT_SAMPLES
    hop_samples = max(1, int(seg_samples * (1.0 - args.segment_overlap)))
    print(f"Segmentation: {seg_samples} samples, hop={hop_samples} (overlap={args.segment_overlap})")

    print("Computing global max magnitude...")
    max_mag = compute_global_max_mag([p[1] for p in train_pairs],
                                     args.stats_sample_pairs, args.workers)
    print(f"  max_mag = {max_mag:.4f}")

    print(f"Building shards (workers={args.workers})...")
    train_ex, train_shards = process_split(train_pairs, args.out_dir, max_mag,
                                           args.samples_per_shard, args.workers,
                                           seg_samples, hop_samples, "train")
    val_ex, val_shards = process_split(val_pairs, args.out_dir, max_mag,
                                       args.samples_per_shard, args.workers,
                                       seg_samples, hop_samples, "val")

    info = {
        "n_freq": Config.N_FREQ_BINS,
        "n_time": Config.N_TIME_FRAMES,
        "sample_rate": Config.SAMPLE_RATE,
        "n_fft": Config.N_FFT,
        "hop_length": Config.HOP_LENGTH,
        "segment_duration": Config.SEGMENT_DURATION,
        "segment_overlap": args.segment_overlap,
        "max_mag": max_mag,
        "train_examples": train_ex,
        "train_shards": train_shards,
        "val_examples": val_ex,
        "val_shards": val_shards,
        "manifest_path": str(args.manifest),
    }
    (args.out_dir / "dataset_info.json").write_text(json.dumps(info, indent=2))
    np.savez(str(args.out_dir / "norm_stats.npz"), max_mag=max_mag)
    print(f"DONE. train: {train_ex} examples / {train_shards} shards;"
          f" val: {val_ex} examples / {val_shards} shards. max_mag={max_mag:.4f}")


if __name__ == "__main__":
    main()
